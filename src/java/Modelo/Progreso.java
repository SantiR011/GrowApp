package Modelo;


public class Progreso {
    int id;
    String porcentaje;

    public Progreso() {
    }

    public Progreso(int id, String porcentaje) {
        this.id = id;
        this.porcentaje = porcentaje;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getPorcentaje() {
        return porcentaje;
    }

    public void setPorcentaje(String porcentaje) {
        this.porcentaje = porcentaje;
    }
    
    
    
    
}
